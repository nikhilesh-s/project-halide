"""Enumerate symmetry-inequivalent Br-for-Cl orderings in the NaBiCl4 primitive cell."""
import hashlib, itertools, json, shutil
from pathlib import Path
import numpy as np, spglib
from pymatgen.core import Structure
from pymatgen.symmetry.analyzer import SpacegroupAnalyzer
from pymatgen.analysis.structure_matcher import StructureMatcher

ROOT = Path(__file__).resolve().parents[2]
DISC = ROOT / "discovery"
IONIC = ROOT / "anish_results/ionic_discovery/structures"
PARENT = IONIC / "qe_pbe_relaxed/NaBiCl4_d3.cif"
BR = IONIC / "alexandria_pbe/NaBiBr4.cif"
LABEL = "PROPOSED MODEL — generated by substitution, unrelaxed, not computed"
SYMPREC = 0.01


def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def sg(s):
    return SpacegroupAnalyzer(s, symprec=SYMPREC).get_space_group_symbol()


def permutations(prim):
    """Atom permutations from the parent's space-group ops (primitive cell => no pure translations)."""
    ops = SpacegroupAnalyzer(prim, symprec=SYMPREC).get_symmetry_operations(cartesian=False)
    fc = prim.frac_coords
    perms = set()
    for op in ops:
        new = op.operate_multi(fc)
        p = []
        for r in new:
            d = fc - r
            d -= np.round(d)
            p.append(int(np.argmin(np.linalg.norm(prim.lattice.get_cartesian_coords(d), axis=1))))
        assert sorted(p) == list(range(len(fc)))
        perms.add(tuple(p))
    return perms


def orderings(prim, cl, x, perms):
    seen, out = set(), []
    for comb in itertools.combinations(cl, x):
        if frozenset(comb) in seen:
            continue
        out.append(comb)
        for p in perms:
            seen.add(frozenset(p[i] for i in comb))
    return out


def write(cid, s, prov):
    d = DISC / "candidates" / cid
    d.mkdir(parents=True, exist_ok=True)
    s = s.copy()
    if "label" in s.site_properties: s.remove_site_property("label")
    s.to(filename=str(d / "structure.cif"))
    prov.update(formula=s.composition.reduced_formula, space_group=sg(s), n_atoms=len(s), label=LABEL)
    (d / "provenance.json").write_text(json.dumps(prov, indent=2))
    return prov


def main():
    parent = Structure.from_file(PARENT)
    prim = parent.get_primitive_structure()
    cl = [i for i, s in enumerate(prim) if s.specie.symbol == "Cl"]
    ds = spglib.get_symmetry_dataset((prim.lattice.matrix, prim.frac_coords, prim.atomic_numbers), symprec=SYMPREC)
    wy = {i: f"{ds.wyckoffs[i]}(orbit {ds.equivalent_atoms[i]})" for i in cl}
    perms = permutations(prim)
    base = dict(parent_file=str(PARENT.relative_to(ROOT)), parent_sha256=sha(PARENT), parent_note="primitive cell of parent")
    rows = []

    # end members
    pb, pm = {**base, "role": "end member x=0 (parent, copied unchanged)"}, None
    d = DISC / "candidates/NBCB-0-parent"; d.mkdir(parents=True, exist_ok=True)
    shutil.copy(PARENT, d / "structure.cif")
    (d / "provenance.json").write_text(json.dumps({**pb, "formula": parent.composition.reduced_formula,
        "space_group": sg(parent), "n_atoms": len(parent), "label": "END MEMBER — QE PBE-D3 relaxed, copied unchanged"}, indent=2))
    rows.append(("NBCB-0-parent", "NaBiCl4", 0, sg(parent), len(parent), "-"))
    brs = Structure.from_file(BR)
    d = DISC / "candidates/NBCB-4-NaBiBr4"; d.mkdir(parents=True, exist_ok=True)
    shutil.copy(BR, d / "structure.cif")
    (d / "provenance.json").write_text(json.dumps({"source_file": str(BR.relative_to(ROOT)), "source_sha256": sha(BR),
        "role": "end member x=4 (Alexandria PBE, copied unchanged)", "formula": brs.composition.reduced_formula,
        "space_group": sg(brs), "n_atoms": len(brs), "label": "END MEMBER — Alexandria PBE, copied unchanged"}, indent=2))
    rows.append(("NBCB-4-NaBiBr4", "NaBiBr4", 4, sg(brs), len(brs), "-"))

    same = StructureMatcher(primitive_cell=True, attempt_supercell=False, ltol=0.3, stol=0.5, angle_tol=10).fit_anonymous(parent, brs)
    counts = {}
    for x in (1, 2, 3):
        z = len(prim) // 6  # formula units per primitive cell
        combos = orderings(prim, cl, x * z, perms)
        sm = StructureMatcher(primitive_cell=False, attempt_supercell=False, scale=False)
        structs = []
        for n, comb in enumerate(combos, 1):
            s = prim.copy()
            for i in comb:
                s.replace(i, "Br")
            structs.append(s)
            cid = f"NBCB-{x}-{n:02d}"
            p = write(cid, s, {**base, "x": x, "replaced_site_indices": list(comb),
                               "replaced_wyckoff": [wy[i] for i in comb], "n_inequivalent_orderings_for_x": len(combos)})
            rows.append((cid, p["formula"], x, p["space_group"], p["n_atoms"], ", ".join(f"{i}:{wy[i]}" for i in comb)))
        # self-check: stoichiometry + no duplicate pairs (matcher run on unrelaxed fixed-lattice structures)
        for s in structs:
            assert s.composition["Br"] == x * z and s.composition["Cl"] == (4 - x) * z
            assert s.composition["Na"] == z and s.composition["Bi"] == z
        for a, b in itertools.combinations(structs, 2):
            assert not sm.fit(a, b), f"duplicate pair at x={x}"
        counts[x] = len(combos)
    idx = ["# Candidate index", "", f"{LABEL}. Primitive-cell ({len(prim)} atoms) substitutions; unrelaxed.", "",
           f"NaBiBr4 same prototype as NaBiCl4 (anonymous StructureMatcher): {same}", "",
           "| ID | formula | x | space group | atoms | replaced sites (index:Wyckoff(orbit)) |", "|---|---|---|---|---|---|"]
    idx += [f"| {' | '.join(map(str, r))} |" for r in rows]
    (DISC / "candidates/INDEX.md").write_text("\n".join(idx) + "\n")
    print("counts", counts, "same_prototype", same, "n_ops", len(perms))
    return counts


if __name__ == "__main__":
    c = main()
    assert all(c[x] >= 1 for x in c)
    print("self-check OK")
